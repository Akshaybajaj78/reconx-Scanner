def scan_ports(
    target: str,
    scan_type: str = "standard",
    ports: Optional[Union[str, Sequence[int]]] = None,
    timeout: int = 60,
    host_timeout: str = DEFAULT_HOST_TIMEOUT,
    timing: str = DEFAULT_TIMING,
    enable_os: bool = False,
    enable_scripts: bool = False,
    scripts: Optional[str] = "banner,vuln,safe",
    grab_banners: bool = True,
    banner_timeout: float = 3.0,
    max_workers: int = 200,
) -> Dict:
    """
    Run an advanced port scan against *target*.

    Strategy:
      1. Try nmap first (if installed & permitted) for service/OS/NSE data.
      2. If nmap returns nothing (blocked/absent), fall back to raw TCP
         socket scanning which works in restricted environments.
    """
    # Determine port list for raw fallback.
    if ports is not None:
        if isinstance(ports, str):
            raw_ports = [int(p.strip()) for p in ports.split(",") if p.strip()]
        else:
            raw_ports = list(ports)
    elif scan_type == "quick":
        raw_ports = TOP_1000_TCP[:100]
    elif scan_type == "udp":
        raw_ports = TOP_1000_TCP[:100]
    elif scan_type == "custom":
        raw_ports = TOP_1000_TCP[:1000]
    else:
        raw_ports = TOP_1000_TCP[:1000]

    # Attempt nmap first.
    nmap_result = scan_ports_nmap(
        target,
        scan_type=scan_type,
        ports=ports,
        timeout=timeout,
        host_timeout=host_timeout,
        timing=timing,
        enable_os=enable_os,
        enable_scripts=enable_scripts,
        scripts=scripts,
        grab_banners=grab_banners,
        max_workers=max_workers,
    )

    if nmap_result["ports"]:
        return nmap_result

    # Fall back to raw TCP socket scanning (works when nmap is blocked).
    raw_open = scan_ports_raw(
        target,
        ports=raw_ports,
        timeout=banner_timeout,
        max_workers=max_workers,
        grab_banners=grab_banners,
    )

    return {
        "target": target,
        "host": _extract_host(target),
        "state": "up" if raw_open else "down",
        "latency": "",
        "os": [],
        "ports": raw_open,
        "summary": {
            "scanned": len(raw_ports),
            "open": len(raw_open),
            "scan_type": f"{scan_type} (raw-tcp)",
        },
    }


