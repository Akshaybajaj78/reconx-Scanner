def _extract_host(target: str) -> str:
    """Pull a bare hostname/IP out of a URL, host:port, or plain string."""
    parsed = urlparse(target if "://" in target else f"//{target}")
    host = parsed.netloc or target
    host = host.split(":")[0]
    return host.strip()


def _is_root() -> bool:
    return os.geteuid() == 0 if hasattr(os, "geteuid") else False


def _grab_banner(host: str, port: int, timeout: float = 3.0) -> Optional[str]:
    """Open a TCP connection and attempt to read a service banner."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.settimeout(timeout)
            sock.connect((host, port))
            probe = b"HEAD / HTTP/1.1\r\nHost: %s\r\nConnection: close\r\n\r\n"
            try:
                sock.sendall(probe % host.encode())
            except Exception:
                pass
            data = sock.recv(1024)
            if not data:
                return None
            text = data.decode("utf-8", errors="replace").strip()
            first_line = text.split("\r\n")[0].split("\n")[0]
            return first_line[:200] or None
    except Exception:
        return None


def _probe_port(host: str, port: int, timeout: float = 3.0) -> Optional[str]:
    """Return a banner string if the port is open, else None."""
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.settimeout(timeout)
            sock.connect((host, port))
            # Try to grab a banner.
            try:
                sock.sendall(b"HEAD / HTTP/1.1\r\nHost: %s\r\nConnection: close\r\n\r\n" % host.encode())
                data = sock.recv(1024)
                if data:
                    text = data.decode("utf-8", errors="replace").strip()
                    first_line = text.split("\r\n")[0].split("\n")[0]
                    if first_line:
                        return first_line[:200]
            except Exception:
                pass
            return ""
    except Exception:
        return None


