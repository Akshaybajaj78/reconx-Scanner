def _resolve_service(port: int, nmap_service: str = "") -> str:
    if nmap_service:
        return nmap_service
    return SERVICE_MAP.get(port, "unknown")


def scan_ports_raw(
    target: str,
    ports: Sequence[int],
    timeout: float = 3.0,
    max_workers: int = 200,
    grab_banners: bool = True,
) -> List[Dict]:
    """Parallel TCP connect scan. Returns list of open-port dicts."""
    host = _extract_host(target)
    open_ports: List[Dict] = []

    def check(port: int) -> Optional[Dict]:
        banner = _probe_port(host, port, timeout=timeout) if grab_banners else None
        if banner is None:
            return None
        service = _resolve_service(port)
        entry = {
            "port": int(port),
            "protocol": "tcp",
            "state": "open",
            "service": service,
            "product": "",
            "version": "",
            "extrainfo": "",
            "banner": banner if banner else None,
            "cpe": [],
            "scripts": {},
        }
        return entry

    with ThreadPoolExecutor(max_workers=max_workers) as pool:
        future_to_port = {pool.submit(check, p): p for p in ports}
        for future in as_completed(future_to_port):
            try:
                result = future.result()
            except Exception:
                result = None
            if result:
                open_ports.append(result)

    open_ports.sort(key=lambda x: x["port"])
    return open_ports


