def _build_nmap_args(
    scan_type: str,
    ports: Optional[Union[str, Sequence[int]]],
    timing: str,
    host_timeout: str,
    enable_os: bool,
    enable_scripts: bool,
    scripts: Optional[str],
) -> str:
    parts: List[str] = [f"-{timing}", "-Pn", f"--host-timeout {host_timeout}"]
    if _is_root():
        parts.append("-sS")
    else:
        parts.append("-sT")

    if scan_type == "quick":
        parts.append("--top-ports 100")
    elif scan_type == "standard":
        parts.extend(["--top-ports 1000", "-sV"])
    elif scan_type == "comprehensive":
        parts.extend(["--top-ports 1000", "-sV"])
        if enable_os:
            parts.append("-O")
        if enable_scripts:
            parts.append("-sC")
            if scripts:
                parts.append(f"--script {scripts}")
    elif scan_type == "udp":
        parts = [p for p in parts if p not in ("-sS", "-sT")]
        parts.extend(["-sU", "-T3", "--top-ports 100"])
    elif scan_type == "custom":
        port_spec = ",".join(str(p) for p in ports) if ports else "1-1000"
        parts.extend(["-p", port_spec, "-sV"])
    else:
        parts.extend(["--top-ports 1000", "-sV"])

    return " ".join(parts)


def scan_ports_nmap(
    target: str,
    scan_type: str = "standard",
    ports: Optional[Union[str, Sequence[int]]] = None,
    timeout: int = 60,
    host_timeout: str = DEFAULT_HOST_TIMEOUT,
    timing: str = DEFAULT_TIMING,
    enable_os: bool = False,
    enable_scripts: bool = False,
    scripts: Optional[str] = "banner,vuln,safe",
    grab_banners: bool = True,
    max_workers: int = 32,
) -> Dict:
    host = _extract_host(target)
    result: Dict = {
        "target": target,
        "host": host,
        "state": "down",
        "latency": "",
        "os": [],
        "ports": [],
        "summary": {"scanned": 0, "open": 0, "scan_type": scan_type},
    }

    if not _HAS_NMAP:
        return result

    try:
        scanner = nmap.PortScanner()
        arguments = _build_nmap_args(
            scan_type, ports, timing, host_timeout, enable_os, enable_scripts, scripts
        )
        scanner.scan(host, arguments=arguments, timeout=timeout)
    except Exception:
        return result

    if host not in scanner.all_hosts():
        return result

    host_data = scanner[host]
    result["state"] = host_data.state()
    result["latency"] = host_data.get("times", {}).get("srtt", "")

    os_matches = host_data.get("osmatch", []) or []
    for om in os_matches:
        result["os"].append(
            {
                "name": om.get("name", ""),
                "accuracy": om.get("accuracy", ""),
                "osclass": om.get("osclass", []),
            }
        )

    open_ports: List[Dict] = []
    for proto in host_data.all_protocols():
        for port in sorted(host_data[proto].keys()):
            port_data = host_data[proto][port]
            if port_data.get("state") != "open":
                continue
            entry: Dict = {
                "port": int(port),
                "protocol": proto,
                "state": port_data.get("state", ""),
                "service": port_data.get("name", ""),
                "product": port_data.get("product", ""),
                "version": port_data.get("version", ""),
                "extrainfo": port_data.get("extrainfo", ""),
                "banner": None,
                "cpe": port_data.get("cpe", []) or [],
                "scripts": port_data.get("script", {}) or {},
            }
            open_ports.append(entry)

    if grab_banners and open_ports:
        banner_targets = [
            (host, e["port"])
            for e in open_ports
            if e["port"] in BANNER_PORTS or e["protocol"] == "tcp"
        ]
        with ThreadPoolExecutor(max_workers=max_workers) as pool:
            future_to_port = {
                pool.submit(_grab_banner, h, p, 3.0): (h, p)
                for h, p in banner_targets
            }
            for future in as_completed(future_to_port):
                _, port = future_to_port[future]
                try:
                    banner = future.result()
                except Exception:
                    banner = None
                for entry in open_ports:
                    if entry["port"] == port and entry["protocol"] == "tcp":
                        entry["banner"] = banner
                        break

    result["ports"] = open_ports
    result["summary"] = {
        "scanned": sum(len(host_data[proto]) for proto in host_data.all_protocols()),
        "open": len(open_ports),
        "scan_type": scan_type,
    }
    return result


